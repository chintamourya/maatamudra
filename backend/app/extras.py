"""Calendar export (.ics), machine-readable obligations export and a tamper-evident fingerprint."""
from __future__ import annotations

import hashlib
import json
from datetime import date, datetime, timezone

from .models import Contract


def fingerprint(c: Contract) -> str:
    """SHA-256 over the agreed terms (spec without provenance) and the clause texts.
    Any later change to a term or clause changes the fingerprint, so two parties can confirm they hold the same text."""
    payload = {
        "type": c.spec.contract_type,
        "spec": c.spec.model_dump(mode="json", exclude={"provenance"}),
        "clauses": [{"key": x.key, "text": x.text} for x in c.clauses],
    }
    return hashlib.sha256(json.dumps(payload, sort_keys=True, ensure_ascii=False).encode()).hexdigest()


def _esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace(";", "\\;").replace(",", "\\,").replace("\n", "\\n")


def build_ics(c: Contract, events: list[dict]) -> str:
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    lines = ["BEGIN:VCALENDAR", "VERSION:2.0", "PRODID:-//Vachan//Contract dates//EN", "CALSCALE:GREGORIAN"]
    for i, e in enumerate(events):
        d: date = e["date"]
        lines += [
            "BEGIN:VEVENT", f"UID:{c.id}-{i}@vachan", f"DTSTAMP:{stamp}", f"DTSTART;VALUE=DATE:{d.strftime('%Y%m%d')}",
            f"SUMMARY:{_esc(e['title'])}", "DESCRIPTION:Generated by Vachan from the agreement terms. Not legal advice.",
            "END:VEVENT",
        ]
    lines.append("END:VCALENDAR")
    return "\r\n".join(lines) + "\r\n"
